export function bandForX100(x100: number): BandId {
  const safe = Math.max(100, x100);
  if (safe < 120) return 1;
  if (safe < 150) return 2;
  if (safe < 200) return 3;
  if (safe < 300) return 4;
  if (safe < 500) return 5;
  if (safe < 1000) return 6;
  if (safe < 10000) return 7;
  return 8;
}

export function getBandSpec(band: BandId): BandSpec {
  return BAND_SPECS[band - 1] ?? BAND_SPECS[0]!;
}

